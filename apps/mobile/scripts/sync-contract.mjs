#!/usr/bin/env node
/**
 * Copies the web app's display contract into `src/contract/`: the `DisplayState` types and the pure
 * helpers a wall display renders with (formatting, words of every language, moments, accents,
 * chart layout, the demo's simulation), so that the app shows a screen exactly like the web.
 *
 *   node scripts/sync-contract.mjs [path/to/SaaS-Monitor]     write src/contract/
 *   node scripts/sync-contract.mjs --check [path]             fail when src/contract/ is stale
 *
 * The web repository defaults to `../SaaS-Monitor` (or `$SAAS_MONITOR_WEB`). Modules are followed
 * from `ENTRIES` through their imports; `@/lib/…` becomes `@/contract/…`. Anything else the web
 * imports must be a package the app has too (`PACKAGES`), or have a stand-in (`STAND_INS`): the
 * script fails rather than copy server or browser code.
 */
import { execFileSync } from "node:child_process";
import { existsSync, mkdirSync, readFileSync, readdirSync, rmSync, writeFileSync } from "node:fs";
import { dirname, join, relative, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const APP_ROOT = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const OUTPUT = join(APP_ROOT, "src", "contract");

/** What the app renders with, relative to the web's `src/lib`. Their imports come along. */
const ENTRIES = [
  "display/types.ts",
  "display/accents.ts",
  "display/backoff.ts",
  "display/chart.ts",
  "display/customer.ts",
  "display/events.ts",
  "display/feed.ts",
  "display/format.ts",
  "display/i18n/index.ts",
  "display/metric.ts",
  "display/milestones.ts",
  "display/moment-queue.ts",
  "display/moments.ts",
  "display/rotation.ts",
  "display/state.ts",
  "display/time.ts",
  "display/demo/state.ts",
  "display/demo/simulation.ts",
  "money.ts",
  "screens/settings.ts",
];

/** Packages the web's display code imports, which the app installs too. */
const PACKAGES = new Set(["zod", "d3-scale", "d3-shape", "d3-time"]);

/**
 * Modules the app can't take whole: browser-only code a pure module imports for a type. Each is
 * replaced by a module of its own, written by `write(webRoot)`.
 */
const STAND_INS = {
  // Sounds play through the Web Audio API: only the names of the sounds cross over.
  "@/lib/sounds": {
    path: "sounds.ts",
    write: (webRoot) => {
      const source = readFileSync(join(webRoot, "src/lib/sounds/index.ts"), "utf8");
      const declaration = source.match(/^export type SoundEvent = [^;]+;$/m);
      if (!declaration) throw new Error("`SoundEvent` is no longer in src/lib/sounds/index.ts");
      return [
        "/** The sounds of moments. The web plays them with the Web Audio API (`src/lib/sounds`). */",
        declaration[0],
      ].join("\n");
    },
  },
  // `moneyFlow` describes amounts for NumberFlow, a web component: its format is `Intl`'s.
  "@number-flow/react": {
    path: "number-flow.ts",
    write: () =>
      [
        "/** Formats of `@number-flow/react`, which follow `Intl.NumberFormat`. */",
        "export type Format = Intl.NumberFormatOptions;",
      ].join("\n"),
  },
};

const IMPORT = /(\bfrom\s+|\bimport\s+)(["'])([^"']+)\2/g;

function header(origin) {
  return `// Generated by scripts/sync-contract.mjs from ${origin}: do not edit.\n\n`;
}

function parseArguments(argv) {
  const check = argv.includes("--check");
  const [path] = argv.filter((argument) => !argument.startsWith("--"));
  const webRoot = resolve(path ?? process.env.SAAS_MONITOR_WEB ?? join(APP_ROOT, "..", "SaaS-Monitor"));
  if (!existsSync(join(webRoot, "src/lib/display/types.ts"))) {
    throw new Error(`No SaaS Monitor web app at ${webRoot}: pass its path.`);
  }
  return { check, webRoot };
}

/** The file of the web's `src/lib` an import names, or `null` for a package. */
function resolveImport(specifier, fromFile, libRoot) {
  let base;
  if (specifier.startsWith("@/lib/")) base = join(libRoot, specifier.slice("@/lib/".length));
  else if (specifier.startsWith(".")) base = resolve(dirname(fromFile), specifier);
  else if (specifier.startsWith("@/")) {
    throw new Error(`${relative(libRoot, fromFile)} imports ${specifier}, outside src/lib`);
  } else return null;
  for (const candidate of [`${base}.ts`, `${base}.tsx`, join(base, "index.ts")]) {
    if (existsSync(candidate)) return candidate;
  }
  throw new Error(`${relative(libRoot, fromFile)} imports ${specifier}, which does not exist`);
}

/** Every module of the contract, from `ENTRIES` through their imports. */
function collect(libRoot) {
  const files = new Map();
  const pending = ENTRIES.map((entry) => join(libRoot, entry));
  while (pending.length > 0) {
    const file = pending.pop();
    if (files.has(file)) continue;
    const source = readFileSync(file, "utf8");
    files.set(file, source);
    for (const [, , , specifier] of source.matchAll(IMPORT)) {
      if (specifier in STAND_INS) continue;
      const imported = resolveImport(specifier, file, libRoot);
      if (imported) pending.push(imported);
      else if (!PACKAGES.has(specifier)) {
        throw new Error(`${relative(libRoot, file)} imports ${specifier}: add it to the app first`);
      }
    }
  }
  return files;
}

function rewrite(source) {
  return source.replace(IMPORT, (match, keyword, quote, specifier) => {
    if (specifier in STAND_INS) {
      const path = STAND_INS[specifier].path.replace(/\.ts$/, "");
      return `${keyword}${quote}@/contract/${path}${quote}`;
    }
    if (specifier.startsWith("@/lib/")) {
      return `${keyword}${quote}@/contract/${specifier.slice("@/lib/".length)}${quote}`;
    }
    return match;
  });
}

function webCommit(webRoot) {
  try {
    return execFileSync("git", ["-C", webRoot, "rev-parse", "--short", "HEAD"], {
      encoding: "utf8",
    }).trim();
  } catch {
    return "unknown";
  }
}

/** The generated files, by path relative to `src/contract/`. */
function generate(webRoot) {
  const libRoot = join(webRoot, "src/lib");
  const output = new Map();
  for (const [file, source] of collect(libRoot)) {
    const path = relative(libRoot, file);
    output.set(path, header(`SaaS-Monitor/src/lib/${path}`) + rewrite(source));
  }
  for (const [specifier, standIn] of Object.entries(STAND_INS)) {
    output.set(standIn.path, header(`SaaS-Monitor (stand-in for ${specifier})`) + `${standIn.write(webRoot)}\n`);
  }
  output.set(
    "source.ts",
    header("SaaS-Monitor") +
      [
        "/** The commit of the web app the contract was copied from. */",
        `export const CONTRACT_SOURCE = ${JSON.stringify(webCommit(webRoot))};`,
        "",
      ].join("\n"),
  );
  return output;
}

function listFiles(directory) {
  if (!existsSync(directory)) return [];
  return readdirSync(directory, { recursive: true, withFileTypes: true })
    .filter((entry) => entry.isFile())
    .map((entry) => relative(directory, join(entry.parentPath, entry.name)));
}

function main() {
  const { check, webRoot } = parseArguments(process.argv.slice(2));
  const output = generate(webRoot);

  if (check) {
    // The commit the files came from may differ: only their contents matter.
    const stale = [...output]
      .filter(([path]) => path !== "source.ts")
      .filter(([path, content]) => {
        const file = join(OUTPUT, path);
        return !existsSync(file) || readFileSync(file, "utf8") !== content;
      })
      .map(([path]) => path);
    const extra = listFiles(OUTPUT).filter((path) => !output.has(path));
    if (stale.length + extra.length > 0) {
      console.error(`src/contract/ is stale: ${[...stale, ...extra].join(", ")}`);
      console.error("Run `node scripts/sync-contract.mjs` and commit the result.");
      process.exit(1);
    }
    console.log(`src/contract/ is up to date (${output.size} files).`);
    return;
  }

  rmSync(OUTPUT, { recursive: true, force: true });
  for (const [path, content] of output) {
    mkdirSync(dirname(join(OUTPUT, path)), { recursive: true });
    writeFileSync(join(OUTPUT, path), content);
  }
  console.log(`Copied ${output.size} files from ${webRoot} into src/contract/.`);
}

main();
