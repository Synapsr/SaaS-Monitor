package com.saasmonitor.core.display

import java.util.Locale

/** Languages a screen speaks (`settings.language`); numbers and dates follow their conventions. */
enum class Language(val code: String, localeTag: String) {
  EN("en", "en-US"),
  FR("fr", "fr-FR"),
  DE("de", "de-DE"),
  ES("es", "es-ES"),
  IT("it", "it-IT"),
  PT("pt", "pt-BR"),
  NL("nl", "nl-NL");

  /** The locale of the screen's numbers and dates, as the web display's `Intl` uses it. */
  val locale: Locale = Locale.forLanguageTag(localeTag)

  val text: DisplayText
    get() = DisplayTexts.of(this)
}

/**
 * The words of a screen that widgets and watches use: a subset of the web display's
 * (`src/lib/display/i18n` of the web app), in every language it speaks. Templates take
 * `{placeholders}`.
 */
class DisplayText(
  val mrrName: String,
  val arrName: String,
  val inThirtyDays: String,
  val goal: String,
  val nextMilestone: String,
  private val toGo: String,
  private val atThisPace: String,
  val today: String,
  val tomorrow: String,
  val revenueToday: String,
  val feedTitle: String,
  val feedEmpty: String,
  val payment: String,
  val customer: String,
  val newSubscription: String,
  val expansion: String,
  val reactivation: String,
  val contraction: String,
  val churn: String,
  val wontRenew: String,
  val paymentFailed: String,
  val paused: String,
  val connectPayment: String,
  val justNow: String,
  private val minutesAgo: String,
  private val hoursAgo: String,
  val yesterday: String,
  val importing: String,
  val failing: String,
  val empty: String,
  val gone: String,
  val locked: String,
  /** A screen without numbers yet whose instance can't be reached. */
  val offline: String,
  // Moments: the titles and words of what just happened (`text.moments` of the web display).
  val paymentReceived: String,
  val newCustomerTitle: String,
  val newSubscriber: String,
  val upgradeTitle: String,
  val welcomeBack: String,
  val downgradeTitle: String,
  val canceledTitle: String,
  val wontRenewTitle: String,
  val paymentFailedTitle: String,
  val pausedTitle: String,
  private val endsOn: String,
  val unpaidDetails: String,
  val connectPaymentTitle: String,
  private val connectFee: String,
  val someoneNew: String,
  private val firstCustomerToday: String,
  private val customersToday: String,
  val catchingUp: String,
  private val onePayment: String,
  private val payments: String,
  private val oneChange: String,
  private val changes: String,
  private val oneCustomer: String,
  private val customers: String,
  val testCelebration: String,
  val testDetails: String,
  val goalReached: String,
  val milestoneReached: String,
) {
  /** "$2,520 to go". */
  fun toGo(amount: String) = toGo.replace("{amount}", amount)

  /** "at this pace: Feb 2027". */
  fun atThisPace(time: String) = atThisPace.replace("{when}", time)

  fun minutesAgo(minutes: Int) = minutesAgo.replace("{minutes}", minutes.toString())

  fun hoursAgo(hours: Int) = hoursAgo.replace("{hours}", hours.toString())

  /** "Ends October 29". */
  fun endsOn(date: String) = endsOn.replace("{date}", date)

  /** "Your fee: $3". */
  fun connectFee(amount: String) = connectFee.replace("{amount}", amount)

  /** "First new customer today", "3 new customers today". */
  fun customersToday(count: Long) =
    if (count == 1L) firstCustomerToday else customersToday.replace("{count}", count.toString())

  fun payments(count: Int) = if (count == 1) onePayment else payments.replace("{count}", "$count")

  fun changes(count: Int) = if (count == 1) oneChange else changes.replace("{count}", "$count")

  fun customers(count: Int) =
    if (count == 1) oneCustomer else customers.replace("{count}", "$count")
}

